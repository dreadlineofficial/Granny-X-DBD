import * as ResEdit from 'resedit';
import * as PE from 'pe-library';
import { readFileSync, writeFileSync } from 'node:fs';
const [exe, ico, ver] = process.argv.slice(2);
const data = readFileSync(exe);
const e = PE.NtExecutable.from(data, { ignoreCert: true });
const res = PE.NtExecutableResource.from(e);
const iconFile = ResEdit.Data.IconFile.from(readFileSync(ico));
const groups = ResEdit.Resource.IconGroupEntry.fromEntries(res.entries);
const gid = groups.length ? groups[0].id : 1, lang = groups.length ? groups[0].lang : 1033;
ResEdit.Resource.IconGroupEntry.replaceIconsForResource(res.entries, gid, lang, iconFile.icons.map(i => i.data));
const vi = ResEdit.Resource.VersionInfo.fromEntries(res.entries)[0];
const [a, b, c] = ver.split('.').map(Number);
vi.setFileVersion(a, b, c, 0, 1033); vi.setProductVersion(a, b, c, 0, 1033);
vi.setStringValues({ lang: 1033, codepage: 1200 }, { ProductName: 'Granny x DBD', FileDescription: 'Granny x DBD', CompanyName: 'froodyofficial-maker', OriginalFilename: 'GrannyxDBD.exe', InternalName: 'GrannyxDBD', LegalCopyright: 'Fan-made game' });
vi.outputToResourceEntries(res.entries);
res.outputResource(e);
writeFileSync(exe, Buffer.from(e.generate()));
console.log('icon + version set on', exe, 'icon group', gid, 'icons', iconFile.icons.length);
